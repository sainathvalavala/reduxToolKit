/*
 * REDUX TOOLKIT FLOW — STEP 4: Use the store in a component (counter)
 * -------------------------------------------------------------------
 * READ:  useSelector() picks a value out of the store and re-renders this
 *        component whenever that value changes.
 * WRITE: useDispatch() returns dispatch; dispatch(inc()) sends the action
 *        { type: "counter/inc" } to the store -> counterSlice's inc reducer
 *        runs -> state.counter.count changes -> useSelector triggers a re-render.
 */
import React from "react";
import { useDispatch, useSelector } from "react-redux";
// action creators generated by createSlice in counterSlice.js
import { dec, inc } from "./counterSlice";

function Counter() {
  // read state.counter.count (key "counter" comes from store.js)
  const count = useSelector((state) => state.counter.count);
  // get the store's dispatch function to send actions
  const dispatch = useDispatch();
  console.log(count);
  return (
    <div>
      <div>
        counter component<br/>
        counter:{count} <br />
        {/* click -> dispatch({ type: "counter/inc" }) -> count + 1 */}
        <button aria-label="Increment value" onClick={() => dispatch(inc())}>
          Increment
        </button>

        {/* click -> dispatch({ type: "counter/dec" }) -> count - 1 */}
        <button aria-label="Decrement value" onClick={() => dispatch(dec())}>
          Decrement
        </button>
      </div>
    </div>
  );
}

export default Counter;
