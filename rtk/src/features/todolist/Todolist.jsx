/*
 * REDUX TOOLKIT FLOW — STEP 4: Use the store in a component (todolist)
 * --------------------------------------------------------------------
 * Global state (the todo list) lives in Redux; local UI state (the text
 * being typed) lives in React's useState — it only goes to Redux on "Add".
 * READ:  useSelector -> state.todolist.todo
 * WRITE: dispatch(add_todo(text)) / dispatch(del_todo(index)) -> reducers in
 *        todolistSlice.js update the array -> component re-renders.
 */
import React, { useState } from "react";
import { useDispatch, useSelector } from "react-redux";
// action creators generated by createSlice in todolistSlice.js
import { add_todo, del_todo } from "./todolistSlice";
function Todolist() {
  // read the todo array from the store
  let x = useSelector((state) => state.todolist.todo);
  console.log(x);
  // dispatch sends actions to the store
  let dispatch = useDispatch();
  // local component state for the input box (not in Redux)
  let [ntd, setntd] = useState("");
  return (
    <div>
      Todolist:{" "}
      <input
        type="text"
        onChange={(e) => {
          setntd(e.target.value);
        }}
      />
      <button
        onClick={() => {
          // { type: "todolist/add_todo", payload: ntd } -> add_todo reducer pushes it
          dispatch(add_todo(ntd));
        }}
      >
        Add todo
      </button>
      <ul>
        {x.map((todo, i) => {
          return (
            <li key={i}>
              {todo}{" "}
              <button
                onClick={() => {
                  // { type: "todolist/del_todo", payload: i } -> del_todo reducer removes index i
                  dispatch(del_todo(i));
                }}
              >
                delete todo
              </button>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

export default Todolist;
